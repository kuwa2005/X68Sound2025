#!/usr/bin/env python3
# Generate src/cp932_table.h : CP932 (Shift_JIS) double-byte -> Unicode table
# so that the Linux build of mxwav needs no iconv / locale data (static binary).
# Usage: python3 tools/gen_cp932_table.py > src/cp932_table.h
LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
out = []
for lead in LEADS:
    for trail in range(0x40, 0xFD):
        cp = 0
        if trail != 0x7F:
            try:
                s = bytes([lead, trail]).decode('cp932')
                if len(s) == 1:
                    cp = ord(s)
            except UnicodeDecodeError:
                pass
        out.append(cp)
print('// Generated by tools/gen_cp932_table.py - DO NOT EDIT')
print('// CP932 double-byte -> Unicode (BMP). Index: lead_index * 189 + (trail - 0x40)')
print('//   lead_index: 0x81-0x9F -> 0-30, 0xE0-0xFC -> 31-59 ; 0 = undefined')
print('#ifndef MXWAV_CP932_TABLE_H\n#define MXWAV_CP932_TABLE_H')
print('static const unsigned short CP932_TABLE[%d] = {' % len(out))
for i in range(0, len(out), 16):
    print('\t' + ','.join('0x%04X' % v for v in out[i:i + 16]) + ',')
print('};\n#endif')
